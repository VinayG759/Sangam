export const STRINGS: Record<Lang, Strings> = { en, kn, hi, te, ta, mr, bn, ur }

const KEY = 'sangam-language'

function initialLanguage(): Lang {
  try {
    const saved = localStorage.getItem(KEY) as Lang | null
    if (saved && saved in STRINGS) return saved
  } catch {
    /* storage blocked: fall through */
  }
  const browser = (navigator.language || 'en').slice(0, 2) as Lang
  return browser in STRINGS ? browser : 'en'
}

/** The resident's chosen language: remembered on this device, and shared by the report and track pages. */
export function useLanguage(): [Lang, (lang: Lang) => void, Strings] {
  const [lang, setLang] = useState<Lang>(initialLanguage)
  useEffect(() => {
    document.documentElement.lang = lang
    return () => { document.documentElement.lang = 'en' }
  }, [lang])
  const choose = (next: Lang) => {
    setLang(next)
    try {
      localStorage.setItem(KEY, next)
    } catch {
      /* not remembered, still works */
    }
  }
  return [lang, choose, STRINGS[lang]]
}

export const isRtl = (lang: Lang) => LANGUAGES.find((l) => l.code === lang)?.rtl ?? false
